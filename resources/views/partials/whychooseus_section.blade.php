document.addEventListener('DOMContentLoaded', function() {
    const observerOptions = { threshold: 0.2, rootMargin: '0px 0px -50px 0px' };
    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) entry.target.classList.add('animate__fadeInUp');
        });
    }, observerOptions);
    document.querySelectorAll('.reason-item').forEach(item => observer.observe(item));
    document.querySelectorAll('.reason-item').forEach(item => {
        item.addEventListener('mouseenter', function(){ this.style.transform = 'translateY(-10px)'; });
        item.addEventListener('mouseleave', function(){ this.style.transform = 'translateY(0)'; });
    });
    const statsObserver = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                const el = entry.target;
                const target = parseInt(el.textContent);
                if (!el.classList.contains('animated') && !isNaN(target)) {
                    let current = 0;
                    const inc = target / 100;
                    const hasPl = el.textContent.includes('+');
                    const timer = setInterval(() => {
                        current += inc;
                        if (current >= target) { el.textContent = target + (hasPl ? '+' : ''); clearInterval(timer); }
                        else { el.textContent = Math.floor(current) + (hasPl ? '+' : ''); }
                    }, 20);
                    el.classList.add('animated');
                }
            }
        });
    }, { threshold: 0.5 });
    document.querySelectorAll('.stat-number').forEach(s => statsObserver.observe(s));
});
</script>