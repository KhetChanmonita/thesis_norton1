    <script>
        // Add animation on scroll
        document.addEventListener('DOMContentLoaded', function() {
            // Simple animation trigger on scroll
            const observerOptions = {
                threshold: 0.2,
                rootMargin: '0px 0px -50px 0px'
            };

            const observer = new IntersectionObserver((entries) => {
                entries.forEach(entry => {
                    if (entry.isIntersecting) {
                        entry.target.classList.add('animate__fadeInUp');
                    }
                });
            }, observerOptions);

            // Observe reason items
            document.querySelectorAll('.reason-item').forEach(item => {
                observer.observe(item);
            });

            // Add hover effects to reason items
            const reasonItems = document.querySelectorAll('.reason-item');

            reasonItems.forEach(item => {
                item.addEventListener('mouseenter', function() {
                    this.style.transform = 'translateY(-10px)';
                });

                item.addEventListener('mouseleave', function() {
                    this.style.transform = 'translateY(0)';
                });
            });

            // Animate stats counter
            const statNumbers = document.querySelectorAll('.stat-number');

            function animateCounter(element, target) {
                let current = 0;
                const increment = target / 100;
                const timer = setInterval(() => {
                    current += increment;
                    if (current >= target) {
                        element.textContent = target + (element.textContent.includes('+') ? '+' : '');
                        clearInterval(timer);
                    } else {
                        element.textContent = Math.floor(current) + (element.textContent.includes('+') ? '+' : '');
                    }
                }, 20);
            }

            const statsObserver = new IntersectionObserver((entries) => {
                entries.forEach(entry => {
                    if (entry.isIntersecting) {
                        const statElement = entry.target;
                        const targetValue = parseInt(statElement.textContent);

                        if (!statElement.classList.contains('animated')) {
                            animateCounter(statElement, targetValue);
                            statElement.classList.add('animated');
                        }
                    }
                });
            }, { threshold: 0.5 });

            statNumbers.forEach(stat => {
                statsObserver.observe(stat);
            });
        });
    </script>
